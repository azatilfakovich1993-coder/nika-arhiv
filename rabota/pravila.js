/* Слова-ловушки: корень сидит внутри другого слова с обратным смыслом.
   «не скользит» — это похвала, а не скол. Такое ловится только списком. */
var STOP = {
  "скол": ["скольз"],
  "бу":   ["буд","был","быв","бук","бум","бут","бух"]
};

function low(s){ return (s || "").toLowerCase().replace(/ё/g, "е"); }

/* Ищем слово только с начала слова: обычная проверка «есть ли подстрока»
   находит «но» внутри «дно», и похвала превращается в жалобу. */
function hasWord(t, w){
  var q = low(w), i = 0, stop = STOP[q] || [];
  while((i = t.indexOf(q, i)) >= 0){
    var prev = i === 0 ? " " : t.charAt(i - 1);
    var wordStart = !/[а-яa-z0-9]/.test(prev);
    var trapped = stop.some(function(s){ return t.substr(i, s.length) === s; });
    if(wordStart && !trapped) return true;
    i += 1;
  }
  return false;
}

/* Где именно в тексте встретилось слово. Нужно, чтобы посмотреть на соседей:
   само по себе слово ещё ничего не значит. */
function gde(t, w){
  var q = low(w), i = 0, stop = STOP[q] || [];
  while((i = t.indexOf(q, i)) >= 0){
    var prev = i === 0 ? " " : t.charAt(i - 1);
    var wordStart = !/[а-яa-z0-9]/.test(prev);
    var trapped = stop.some(function(s){ return t.substr(i, s.length) === s; });
    if(wordStart && !trapped) return i;
    i += 1;
  }
  return -1;
}

/* Отрицание переворачивает смысл. «Не хлипкая», «сколов нет», «не ржавеет» —
   это похвала, а не жалоба. На выдуманных отзывах такого не встречалось,
   а в настоящих это каждый десятый. Смотрим, что стоит рядом. */
/* Границу слова (\b) здесь использовать нельзя: в JavaScript она знает только
   латиницу, и после русского «нет» никакой границы не видит. Проверяем сами. */
var RE_NE_DO = /(^|[\s,.;:!?(])(не|без|ни)\s+[а-яa-z]*$/;
var RE_NET_POSLE = /^[а-яa-z]*\s*(нет|не\s+было)(?![а-яa-z])/;

function otricanie(t, i, w){
  var do_ = t.slice(Math.max(0, i - 12), i);
  if(RE_NE_DO.test(do_)) return true;
  var posle = t.slice(i + w.length, i + w.length + 14);
  if(RE_NET_POSLE.test(posle)) return true;
  return false;
}

/* Общие слова про поломку могут относиться к упаковке, а не к изделию:
   «упаковка очень хлипкая» — это упаковка, а не брак сушилки. */
var OBSHIE = ["хлипк","порван","мятая","царапин","потертост","потёртост"];
/* Между «упаковка» и «хлипкая» обычно ещё пара слов: «упаковка, очень хлипкая».
   Поэтому не требуем, чтобы слова стояли вплотную, — просто смотрим, шла ли
   речь про упаковку в ближайших сорока знаках. */
var RE_PRO_UPAK = /(упаковк|упакован|коробк|пленк|плёнк)/;

function najti(text, slovar){
  var t = low(text), hits = [];
  Object.keys(slovar).forEach(function(cat){
    slovar[cat].forEach(function(w){
      var i = gde(t, w);
      if(i < 0) return;
      // «Не хлипкая» — похвала, и отрицание её отменяет. Но «ножки не держат» —
      // это сама примета, она в словаре так и записана. Такие не отменяем.
      if(!/^(не|без|ни)\s/.test(w) && otricanie(t, i, low(w))) return;
      // Окно нарочно узкое. «Упаковка, очень хлипкая» — про упаковку.
      // «Упаковка вскрыта, прутья хлипкие» — про прутья, и это уже две разные
      // претензии, пусть их разделяет нейросеть.
      var realCat = cat;
      if(OBSHIE.indexOf(w) >= 0 && RE_PRO_UPAK.test(t.slice(Math.max(0, i - 20), i))){
        realCat = "upak";                          // жалоба на упаковку, не на изделие
      }
      hits.push({cat:realCat, word:w});
    });
  });
  return hits;
}

function catById(id){
  for(var i = 0; i < CATS.length; i++) if(CATS[i].id === id) return CATS[i];
  return null;
}

/* Разбор одного отзыва.
   layer "code" — хватило правил, нейросеть не нужна;
   layer "ai"   — правила не справились, отзыв уходит модели. */
function classify(o){
  var text = (o.text || "").trim();
  var t = low(text);

  var problemy = najti(text, PROBLEMA);
  var cats = [];
  problemy.forEach(function(h){ if(cats.indexOf(h.cat) < 0) cats.push(h.cat); });

  var hvalyat = POHVALA.some(function(w){ return hasWord(t, w) || t.indexOf(low(w)) >= 0; });

  // 1. Совсем пусто — разбирать нечего.
  var bukvy = t.replace(/[^а-яa-z]/g, "");
  if(bukvy.length < 3 && !hvalyat){
    return {cats:["musor"], main:"musor", layer:"code", why:"текста нет"};
  }

  // 2. Есть претензия и только одного вида — правил хватило.
  if(cats.length === 1){
    var slova = problemy.filter(function(h){ return h.cat === cats[0]; })
                        .map(function(h){ return "«" + h.word + "»"; });
    return {cats:cats, main:cats[0], layer:"code",
            why:"по словам: " + slova.slice(0, 3).join(", ")};
  }

  /* 3. Претензий несколько видов. Но приоритет — претензия к товару важнее
        претензии к цене и к заказу — может оставить одну. Тогда спрашивать
        нейросеть не о чем и платить не за что. */
  var glav = glavnye(cats);
  if(glav.length === 1){
    var odna = problemy.filter(function(h){ return h.cat === glav[0]; })
                       .map(function(h){ return "«" + h.word + "»"; });
    return {cats:cats, main:glav[0], layer:"code",
            why:"претензия к товару важнее прочего, по словам: " +
                odna.slice(0, 3).join(", ")};
  }

  // 4. Осталось несколько равных — какая главная, решает нейросеть.
  if(cats.length > 1){
    return {cats:cats, main:null, layer:"ai",
            why:"сразу несколько видов претензий: " +
                cats.map(function(c){ return catById(c).name.toLowerCase(); }).join(", ")};
  }

  // 4. Претензий нет, но хвалят — хороший отзыв, даже если он в одно слово.
  if(hvalyat){
    return {cats:["horosh"], main:"horosh", layer:"code", why:"похвала, претензий нет"};
  }

  // 5. Ни примет проблемы, ни похвалы — по словам не понять.
  return {cats:[], main:null, layer:"ai", why:"знакомых слов нет"};
}

/* Претензии к самому изделию важнее претензий к цене и к заказу.
   Если человек пишет «пришла кривая, упаковка порвана, да ещё и дорого» —
   главное тут не цена. Раньше это было просьбой к нейросети, и она её
   не слушалась. Теперь это правило: цена и заказ выбывают из вариантов,
   когда есть претензия к товару. */
var PRO_TOVAR = ["brak", "upak", "komplekt", "peresort", "opisanie"];

function glavnye(cats){
  if(!cats || cats.length < 2) return cats || [];
  var est = cats.filter(function(c){ return PRO_TOVAR.indexOf(c) >= 0; });
  return est.length ? est : cats;
}

/* Какие именно приметы нашлись в тексте. Нужно, чтобы в отчёте писать не
   «20 жалоб на брак», а «в 17 из них про ножки, в 9 про то, что не держатся». */
function primety(text){
  return najti(text, PROBLEMA).map(function(h){ return h.word; });
}

module.exports = {CATS:CATS, classify:classify, catById:catById,
                  hasWord:hasWord, low:low, primety:primety, glavnye:glavnye};
